import numpy as np, json, sys, matplotlib
matplotlib.use('Agg'); import matplotlib.pyplot as plt
sys.path.insert(0,'/box/final'); from burgers2d import *
d = np.load('/box/final/snaps_N512.npz'); err = json.load(open('/box/final/errors.json'))
times = [0.0,0.5,1.0,1.5,1.75,2.0]; N = 512; dx = L/N; xc = (np.arange(N)+0.5)*dx
INK, MUTED, GRID = '#1f1f1d', '#6b6a64', '#e1e0d9'; C1, C2, C3 = '#2a78d6', '#eb6834', '#1baf7a'
plt.rcParams.update({'font.size':9,'axes.edgecolor':'#c3c2b7','axes.labelcolor':INK,'xtick.color':MUTED,'ytick.color':MUTED})
fig = plt.figure(figsize=(18,10.5)); gs = fig.add_gridspec(3,6,height_ratios=[1.15,0.8,0.95],hspace=0.45,wspace=0.3)
for k,t in enumerate(times):
    u = d[f"t{t}"]; ax = fig.add_subplot(gs[0,k])
    im = ax.imshow(u.T, origin='lower', extent=[0,L,0,L], cmap='cividis', vmin=-1/3, vmax=1)
    ax.set_title(f"t = {t:g}", color=INK); ax.set_xlabel('x')
    if k==0: ax.set_ylabel('y')
    ax.set_xticks([0,2*np.pi,4*np.pi],['0','2π','4π']); ax.set_yticks([0,2*np.pi,4*np.pi],['0','2π','4π'])
    ax2 = fig.add_subplot(gs[1,k]); ue = exact(xc+xc[0], t)
    ax2.plot(xc, ue, color=INK, lw=1.2, label='exact (Lax–Oleinik)')
    ax2.plot(xc[::4], u[::4,0], 'o', ms=3, color=C1, label='WENO5, N=512')
    ax2.set_xlim(0,L); ax2.set_ylim(-0.45,1.1); ax2.grid(color=GRID,lw=0.5); ax2.set_xlabel('x  (cut at y = Δx/2)')
    ax2.set_xticks([0,2*np.pi,4*np.pi],['0','2π','4π'])
    ax2.set_title(f"L1 err = {err['512'][str(t)]['L1']:.1e}", fontsize=8, color=MUTED)
    if k==0: ax2.set_ylabel('u'); ax2.legend(fontsize=7, frameon=False, loc='lower left')
cb = fig.colorbar(im, ax=fig.axes[0:12:2], orientation='vertical', fraction=0.02, pad=0.01); cb.set_label('u')
bot = gs[2,:].subgridspec(1,3,wspace=0.42)
ax = fig.add_subplot(bot[0]); Ns = sorted(int(n) for n in err)
for t,c in [(0.5,C1),(1.0,C3),(2.0,C2)]:
    e = [err[str(n)][str(t)]['L1'] for n in Ns]; ax.loglog(Ns, e, 'o-', color=c, lw=2, ms=6, label=f't={t:g}')
    ax.annotate(f't={t:g}', (Ns[-1], e[-1]), xytext=(6,0), textcoords='offset points', color=INK, fontsize=8, va='center')
n = np.array(Ns,float); ax.loglog(n, 2e-6*(n/64)**-5, '--', color=MUTED, lw=1); ax.loglog(n, 1.5e-2*(n/64)**-1, ':', color=MUTED, lw=1)
ax.text(n[2], 2e-6*(n[2]/64)**-5*0.25, 'slope −5', color=MUTED, fontsize=8); ax.text(n[1], 1.5e-2*(n[1]/64)**-1*1.4, 'slope −1', color=MUTED, fontsize=8)
ax.set_xlabel('N (grid points per direction)'); ax.set_ylabel('L1 error vs exact'); ax.grid(color=GRID,lw=0.5,which='both'); ax.legend(frameon=False,fontsize=8)
ax.set_title('Grid convergence (smooth: t≤1, shocked: t=2)', color=INK)
ax = fig.add_subplot(bot[1]); e2 = d["t2.0"]-point_exact(N,2.0)
im2 = ax.imshow(np.log10(np.abs(e2).T+1e-16), origin='lower', extent=[0,L,0,L], cmap='Blues', vmin=-12, vmax=0)
fig.colorbar(im2, ax=ax, fraction=0.046).set_label('log10 |u − u_exact|'); ax.set_title('Pointwise error at t=2 (N=512)', color=INK)
ax.set_xlabel('x'); ax.set_ylabel('y')
ax = fig.add_subplot(bot[2]); s = np.linspace(0,L,4000)
for t,c,lab in [(1.0,C1,'t=1'),(1.5,C3,'t=1.5 (breaking)'),(2.0,C2,'t=2')]: ax.plot(s, exact(s,t), color=c, lw=2, label=lab)
ax.plot(s, u0f(s), color=MUTED, lw=1, ls='--', label='t=0')
ax.set_xlabel('s = x + y  (mod 4π)'); ax.set_ylabel('u'); ax.grid(color=GRID,lw=0.5); ax.legend(frameon=False,fontsize=8)
ax.set_title('Exact 1-D profile u(s,t); shock at s = 2π + 2t/3', color=INK)
fig.suptitle("2D inviscid Burgers  u_t + u u_x + u u_y = 0,  u0 = 1/3 + (2/3) sin((x+y)/2),  periodic [0,4π]²   —  shock forms at t = 1.5", fontsize=12, color=INK)
fig.savefig('/box/final/summary_all.png', dpi=130, bbox_inches='tight')
